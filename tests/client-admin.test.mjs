import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,rm } from 'node:fs/promises';
import { join,resolve,dirname,basename } from 'node:path';
import { tmpdir } from 'node:os';
import { ClientAccess } from '../src/client-access.mjs';
import { ClientAdmin } from '../src/client-admin.mjs';
test('admin lifecycle routes use the real account store and never return saved credential digests',async t=>{
  const folder=await mkdtemp(join(tmpdir(),'bifrost-client-admin-'));
  t.after(async()=>{assert.equal(resolve(dirname(folder)),resolve(tmpdir()));assert.ok(basename(folder).startsWith('bifrost-client-admin-'));await rm(folder,{recursive:true,force:true});});
  const model='claude-codebuddy-opus-5-5';
  const access=await ClientAccess.open({path:join(folder,'access.json'),allowedModelIds:[model]});
  t.after(()=>access.close());
  const admin=new ClientAdmin({access,getModels:()=>[{id:model}],getEndpoint:()=>({portalUrl:'http://localhost/portal'})});
  const created=await admin.mutate('/api/client-admin/accounts',{username:'sample',password:'sample-secret-password',allowedModels:[model],enabled:true});
  const root='/api/client-admin/accounts/'+created.account.id;
  const key=await admin.mutate(root+'/keys',{name:'Desktop',expiresInDays:1});
  assert.ok(access.authenticateKey(key.secret));
  assert.equal((await admin.mutate(root,{enabled:false})).account.enabled,false);
  assert.equal(access.authenticateKey(key.secret),null);
  await admin.mutate(root,{enabled:true});
  await admin.mutate(root+'/keys/'+key.key.id,{enabled:false});
  assert.equal(access.authenticateKey(key.secret),null);
  await admin.mutate(root+'/keys/'+key.key.id+'/revoke',{});
  const invite=await admin.mutate('/api/client-admin/invites',{expiresInDays:1,maxUses:2,allowedModels:[model]});
  await admin.mutate('/api/client-admin/invites/'+invite.invite.id+'/revoke',{});
  await admin.mutate('/api/client-admin/registration',{mode:'closed'});
  const snapshot=await admin.snapshot();
  assert.equal(snapshot.registration.mode,'closed');assert.equal(snapshot.accounts[0].keys[0].status,'revoked');
  assert.equal(snapshot.invites[0].status,'revoked');assert.doesNotMatch(JSON.stringify(snapshot),/sample-secret-password|"hash"|"salt"|bfk_|bfi_/);
  await assert.rejects(admin.mutate(root+'/keys/'+key.key.id+'/revoke',{unknown:true}),e=>e.status===400);
  await assert.rejects(admin.mutate('/api/client-admin/nonexistent',{}),e=>e.status===404);
});
